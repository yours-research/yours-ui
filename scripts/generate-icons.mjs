import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const ICONS_DIR = path.join(ROOT, 'src', 'icons');
const OUT_FILE = path.join(ICONS_DIR, 'iconData.ts');

const SUPPORTED_TAGS = new Set(['path', 'line', 'circle', 'rect', 'ellipse', 'polyline', 'polygon']);

const ATTR_MAP = {
  'stroke-width': 'strokeWidth',
  'stroke-linecap': 'strokeLinecap',
  'stroke-linejoin': 'strokeLinejoin',
  'fill-opacity': 'fillOpacity',
  'stroke-opacity': 'strokeOpacity',
  'fill-rule': 'fillRule',
  'clip-rule': 'clipRule',
};

function parseAttributes(attrText) {
  const attrs = {};
  const attrRe = /([a-zA-Z0-9:-]+)\s*=\s*"([^"]*)"/g;
  let m;
  while ((m = attrRe.exec(attrText)) !== null) {
    const rawKey = m[1];
    const key = ATTR_MAP[rawKey] ?? rawKey;
    attrs[key] = m[2];
  }
  return attrs;
}

function parseSvgPrimitives(svgSource, fileName) {
  if (!/viewBox\s*=\s*"0 0 24 24"/.test(svgSource)) {
    throw new Error(`Expected viewBox="0 0 24 24" in ${fileName}`);
  }
  const innerMatch = svgSource.match(/<svg[^>]*>([\s\S]*?)<\/svg>/i);
  if (!innerMatch) {
    throw new Error(`Could not locate <svg> body in ${fileName}`);
  }
  const body = innerMatch[1].trim();
  const primitives = [];
  const elRe = /<([a-zA-Z0-9]+)\b([^>]*?)(?:\/>|><\/\1>)/g;
  let m;
  while ((m = elRe.exec(body)) !== null) {
    const tag = m[1].toLowerCase();
    if (!SUPPORTED_TAGS.has(tag)) {
      throw new Error(`Unsupported SVG element <${tag}> in ${fileName}`);
    }
    primitives.push({
      tag,
      attrs: parseAttributes(m[2]),
    });
  }
  if (primitives.length === 0) {
    throw new Error(`No SVG primitives parsed in ${fileName}`);
  }
  return primitives;
}

const files = fs
  .readdirSync(ICONS_DIR)
  .filter((f) => f.endsWith('.svg'))
  .sort((a, b) => a.localeCompare(b));

const iconEntries = files.map((file) => {
  const name = file.replace(/\.svg$/, '');
  const raw = fs.readFileSync(path.join(ICONS_DIR, file), 'utf8');
  return [name, parseSvgPrimitives(raw, file)];
});

const namesUnion = iconEntries.map(([name]) => `  | '${name}'`).join('\n');
const namesTuple = iconEntries.map(([name]) => `  '${name}',`).join('\n');
const dataObject = JSON.stringify(Object.fromEntries(iconEntries), null, 2);

const output = `/* Auto-generated by scripts/generate-icons.mjs from src/icons/*.svg. Do not edit manually. */

export type ApertureIconPrimitiveTag =
  | 'path'
  | 'line'
  | 'circle'
  | 'rect'
  | 'ellipse'
  | 'polyline'
  | 'polygon';

export interface ApertureIconPrimitive {
  readonly tag: ApertureIconPrimitiveTag;
  readonly attrs: Readonly<Record<string, string>>;
}

export type ApertureIconName =
${namesUnion};

export const APERTURE_ICON_NAMES: readonly ApertureIconName[] = [
${namesTuple}
] as const;

export const APERTURE_ICON_DATA: Readonly<Record<ApertureIconName, readonly ApertureIconPrimitive[]>> = ${dataObject};
`;

fs.writeFileSync(OUT_FILE, output, 'utf8');
console.log(`Generated ${iconEntries.length} typed Aperture icons -> src/icons/iconData.ts`);
